package eu.wohlben.qits.maintenance.automation;

import eu.wohlben.qits.maintenance.entity.MtBump;
import eu.wohlben.qits.maintenance.persistence.MaintenanceStore;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import org.jboss.logging.Logger;

/**
 * <b>A {@code dependency-bump} that never reached main leaves its repository owed a prompt re-offer
 * against main</b> (qits-1578, qits-2290). The dispatcher sorts a marked repository first and clears
 * the mark when it opens the main-only request; nothing is ever committed onto a closed request.
 *
 * <p>Two ways a bump is stranded, and both end here:
 *
 * <ul>
 *   <li><b>SUPERSEDED on a closed request</b> (qits-1578): the request closed before, or while, the
 *       row ran — {@code AutomationService} calls {@link #owedAReoffer} as it supersedes it.
 *   <li><b>COMMITTED onto a fold that then RELEASED</b> (qits-2290): the run went green and pushed
 *       its pin onto the request's source branch while fold F was already building; qits-projects
 *       deliberately does not refold for that push and releases F. A commit made on top of F is by
 *       construction not in F, so a row COMMITTED at exactly the released {@code mergedSha} is a bump
 *       that was lost — {@link #releasedAt}. Live: qits-system-service-rr-252, row COMMITTED at
 *       f4eb5de, the request RELEASED with {@code mergedSha} f4eb5de. A row COMMITTED at an older
 *       fold was folded into a later one and is shipped; it marks nothing.
 * </ul>
 *
 * <p>Only {@code dependency-bump} rows mark: the mark re-offers a dependency bump, and every other
 * kind is regenerated by the next request's own fold. The store keeps the first mark, so a stranding
 * announced twice marks once.
 */
@ApplicationScoped
public class StrandedBumpReoffer {

  private static final Logger LOG = Logger.getLogger(StrandedBumpReoffer.class);

  @Inject MaintenanceStore store;

  /** Marks the row's repository owed a re-offer when the row is a {@code dependency-bump}. */
  public void owedAReoffer(MtBump row) {
    if (DependencyBumpAutomation.KIND.equals(row.automationKind)) {
      store.markReofferOwed(row.repository, Instant.now());
    }
  }

  /**
   * <b>THE RELEASED FOLD (qits-2290)</b>: a request released at {@code mergedSha}; every {@code
   * dependency-bump} row of it that COMMITTED at that very fold wrote a commit the release does not
   * carry, and its repository is marked owed a re-offer. Answers the rows that marked.
   *
   * @param requestId qits-projects' request id, as the rows carry it
   * @param requestName the qualified id to name in the log, or null for the id
   * @param mergedSha the fold the request released
   */
  public List<MtBump> releasedAt(String requestId, String requestName, String mergedSha) {
    List<MtBump> stranded = new ArrayList<>();
    for (MtBump row : store.automations(requestId, mergedSha)) {
      if (!DependencyBumpAutomation.KIND.equals(row.automationKind)
          || AutomationState.of(row.status) != AutomationState.COMMITTED
          || row.resultSha == null
          || !mergedSha.equals(row.foldSha)) {
        continue;
      }
      owedAReoffer(row);
      stranded.add(row);
      LOG.infof(
          "Release request %s released fold %s without the dependency bump %s committed on top of"
              + " it as %s; %s is owed a re-offer against main",
          requestName == null ? requestId : requestName,
          abbreviate(mergedSha),
          row.id,
          abbreviate(row.resultSha),
          row.repository);
    }
    return stranded;
  }

  private static String abbreviate(String sha) {
    return sha == null || sha.length() <= 12 ? sha : sha.substring(0, 12);
  }
}
